function removeStaleRecipePages(recipesDir, expectedIds) {
  if (!fs.existsSync(recipesDir)) return;
  for (const entry of fs.readdirSync(recipesDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || expectedIds.has(entry.name)) continue;
    const indexPath = path.join(recipesDir, entry.name, "index.html");
    if (!fs.existsSync(indexPath)) continue;
    const content = fs.readFileSync(indexPath, "utf8");
    if (content.includes(GENERATED_MARKER)) fs.rmSync(path.join(recipesDir, entry.name), { recursive: true });
  }
}

function generateEditorialPages({ recipes, categories, guide, temperatures, wines, root = ROOT }) {
  const recipesDir = path.join(root, "recettes");
  const guidesDir = path.join(root, "guides");
  const ids = new Set(recipes.map(recipe => recipe.id));
  removeStaleRecipePages(recipesDir, ids);

  for (const recipe of recipes) {
    if (!recipe.id || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(recipe.id)) throw new Error(`Invalid editorial recipe id: ${recipe.id || recipe.nom}`);
    const related = recipes.filter(candidate => candidate.id !== recipe.id && candidate.cat === recipe.cat).slice(0, 3);
    writeFile(path.join(recipesDir, recipe.id, "index.html"), renderRecipePage(recipe, categories, related));
  }
  writeFile(path.join(recipesDir, "index.html"), renderCatalogue(recipes, categories));
  writeFile(path.join(guidesDir, "index.html"), renderGuideIndex());

  const content = { guide, temperatures, wines: staticWineGuide(wines), methodology: methodologyHtml(recipes.length) };
  for (const definition of GUIDE_DEFINITIONS) {
    writeFile(path.join(guidesDir, definition.id, "index.html"), renderGuidePage(definition, content[definition.key], recipes.length));
  }

  const urls = [
    `${SITE_URL}/`,
    `${SITE_URL}/recettes/`,
    ...recipes.map(recipe => `${SITE_URL}/recettes/${recipe.id}/`),
    `${SITE_URL}/guides/`,
    ...GUIDE_DEFINITIONS.map(guideDefinition => `${SITE_URL}/guides/${guideDefinition.id}/`)
  ];
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(url => `  <url><loc>${escapeHtml(url)}</loc></url>`).join("\n")}\n</urlset>\n`;
  writeFile(path.join(root, "sitemap.xml"), sitemap);
  writeFile(path.join(root, "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);

  return { recipes: recipes.length, guides: GUIDE_DEFINITIONS.length, urls: urls.length };
}

function main() {
  const recipes = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "recipes.json"), "utf8"));
  const categories = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "categories.json"), "utf8"));
  const read = name => fs.readFileSync(path.join(ROOT, "data", name), "utf8");
  const result = generateEditorialPages({
    recipes,
    categories,
    guide: read("guide.html"),
    temperatures: read("temperatures.html"),
    wines: read("vins.html")
  });
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}

